/** 게임의 지금 버전 = 그 게임 가짜 리뷰 중 가장 높은 버전(리뷰가 없으면 v1.0) */
export function sampleVersion(slug: string): string {
	const num = (v: string) => v.slice(1).split('.').map(Number);
	const newer = (a: string, b: string) => {
		const [a1 = 0, a2 = 0] = num(a);
		const [b1 = 0, b2 = 0] = num(b);
		return a1 !== b1 ? a1 > b1 : a2 > b2;
	};
	return REVIEW_ROWS.filter((r) => r[0] === slug)
		.map((r) => r[3])
		.reduce((best, v) => (newer(v, best) ? v : best), 'v1.0');
}

/** 게임별 가짜 리뷰 수 — 카드 · 탭의 리뷰 수를 목록과 맞춘다 */
export function sampleReviewCount(slug: string): number {
	return REVIEW_ROWS.filter((r) => r[0] === slug).length;
}
